"""09 - Assemble reports/RESULTS.md from pipeline outputs. Every number here is read from outputs/."""

from __future__ import annotations

import json
from datetime import date

import pandas as pd

from gmcn.config import OUTPUTS, REPORTS, ensure_dirs


def md(df: pd.DataFrame, floatfmt: dict | None = None) -> str:
    floatfmt = floatfmt or {}
    cols = list(df.columns)
    out = ["| " + " | ".join(cols) + " |", "| " + " | ".join("---" for _ in cols) + " |"]
    for _, r in df.iterrows():
        cells = []
        for c in cols:
            v = r[c]
            if isinstance(v, float):
                cells.append(floatfmt.get(c, "{:.2f}").format(v))
            else:
                cells.append(str(v))
        out.append("| " + " | ".join(cells) + " |")
    return "\n".join(out)


def load_json(name: str) -> dict:
    p = OUTPUTS / name
    return json.loads(p.read_text()) if p.exists() else {}


def main() -> None:
    ensure_dirs()
    L = [f"# Results", "", f"Generated by `bash run.sh` on {date.today().isoformat()} from the committed data snapshots "
         "(see `data/raw/SOURCES.md`). Every figure and number below is produced by the pipeline; nothing is typed in by hand.", ""]

    # ---------------------------------------------------------------- network
    ns = load_json("network_summary.json")
    fy, py = ns["focal_year"], ns["prior_year"]
    comp = pd.read_csv(OUTPUTS / "network_concentration_change.csv", dtype={"hts6": str})
    L += ["## 1. Supply-network concentration (US imports, HTS 6-digit)", "",
          f"![Supply network](../figures/fig00_supply_network.png)", "",
          f"{ns['n_lines_neff_below_2']} of {ns['n_lines']} import lines behave like fewer than two equal suppliers in {fy} "
          f"(effective number of suppliers = 1/HHI < 2).", "",
          "![Concentration](../figures/fig01_import_concentration.png)", ""]
    t = comp.sort_values("hhi", ascending=False)[["commodity", "value_usd", "hhi", "n_eff_hhi", "top1_country", "top1_share",
                                                  f"top1_country_{py}", f"top1_share_{py}"]].copy()
    t["value_usd"] = t["value_usd"] / 1e6
    t = t.rename(columns={"value_usd": f"{fy} value, $M", "hhi": "HHI", "n_eff_hhi": "N_eff",
                          "top1_country": f"top supplier {fy}", "top1_share": "share",
                          f"top1_country_{py}": f"top supplier {py}", f"top1_share_{py}": f"share {py}"})
    L += [md(t, {f"{fy} value, $M": "{:,.1f}", "HHI": "{:.3f}", "N_eff": "{:.2f}", "share": "{:.0%}", f"share {py}": "{:.0%}"}), ""]
    if ns.get("top1_changes"):
        L += [f"**Top supplier changed between {py} and {fy}:** " +
              "; ".join(f"{c['commodity']} ({c['from']} to {c['to']}"
                        + (", thin line under $10M" if c.get("value_usd", 1e12) < 1e7 else "") + ")"
                        for c in ns["top1_changes"]) + ".", ""]

    L += ["### Centrality, communities and nestedness", "",
          "Highest betweenness (countries bridging otherwise separate commodity supply chains): " +
          ", ".join(f"{r['country']} ({r['betweenness']:.2f})" for r in ns["top_betweenness"]) + ".", "",
          "Highest eigenvector centrality in the country projection: " +
          ", ".join(f"{r['country']} ({r['eigenvector']:.2f})" for r in ns["top_eigenvector"]) + ".", "",
          "![Co-dependency](../figures/fig02_codependency.png)", "",
          "Co-dependency communities (commodities whose supplier profiles overlap, so one disruption hits all of them): " +
          " | ".join(", ".join(c) for c in ns["communities"]) + ".", ""]
    n = ns["nestedness"]
    L += [f"Nestedness NODF = {n['nodf']:.1f} vs {n['null_mean']:.1f} ± {n['null_sd']:.1f} under a fixed-degree null "
          f"(z = {n['z']:.2f}, one-sided p = {n['p_greater']:.2f}). The supplier-commodity structure is **not** more nested "
          "than its degree sequence implies: concentration comes from a few dominant suppliers per line, not from a hidden "
          "nested hierarchy.", ""]

    R = ns["robustness_R"]
    L += ["### Robustness and scenarios", "", "![Robustness](../figures/fig03_robustness.png)", "",
          f"Removing the three most dominant suppliers ({', '.join(ns['top3_dominance_order'])}) leaves "
          f"{ns['retained_after_top3_dominance']:.0%} of supply (equal-weighted across commodities); removing the three "
          f"largest by trade value ({', '.join(ns['top3_strength_order'])}) leaves {ns['retained_after_top3_strength']:.0%}. "
          f"Robustness index R (mean retained over all removal steps): targeted-by-dominance {R['targeted_dominance']:.3f}, "
          f"targeted-by-value {R['targeted_strength']:.3f}, random {R['random_mean']:.3f}.", "",
          "![China scenario](../figures/fig05_china_scenario.png)", ""]
    sc = pd.read_csv(OUTPUTS / "network_scenarios.csv", dtype={"hts6": str, "year": str})
    piv = sc[sc.year == fy].pivot_table(index="commodity", columns="scenario", values="loss_share")
    piv = piv[(piv > 0.10).any(axis=1)]
    piv = piv.loc[piv.max(axis=1).sort_values(ascending=False).index].reset_index()
    L += [f"Supply lost per scenario, {fy} (lines with > 10 % loss in any scenario):", "",
          md(piv, {c: "{:.0%}" for c in piv.columns if c != "commodity"}), ""]

    sar = pd.read_csv(OUTPUTS / f"network_supply_at_risk_{fy}.csv", dtype={"hts6": str})
    mc = ns["mc"]
    w = sar.pivot_table(index=["commodity", "hhi"], columns="rho", values="es_95").reset_index().sort_values("hhi", ascending=False)
    w.columns = ["commodity", "HHI"] + [f"ES95 rho={c}" for c in w.columns[2:]]
    L += ["### Monte Carlo supply-at-risk", "", "![Supply at risk](../figures/fig04_supply_at_risk.png)", "",
          f"Every supplier fails independently with p = {mc['p']:.0%} a year (an illustrative prior), so expected loss is "
          f"{mc['expected_loss_range'][0]:.1%}-{mc['expected_loss_range'][1]:.1%} for every line. Concentration only moves "
          f"the tail: the correlation between HHI and the 95 % expected shortfall is {mc['corr_es95_vs_hhi_rho0']:.2f}. "
          "Correlated failures (a common geopolitical factor, rho > 0) fatten the tail of the diversified lines most.", "",
          md(w.head(8), {"HHI": "{:.3f}", **{c: "{:.0%}" for c in w.columns[2:]}}), ""]

    bx = pd.read_csv(OUTPUTS / "network_export_buyers.csv", dtype={"hts6": str})
    bx = bx[["commodity", "value_usd", "n_eff_hhi", "top1_country", "top1_share", f"n_eff_hhi_{py}",
             f"top1_country_{py}", f"top1_share_{py}"]].copy()
    bx["value_usd"] = bx["value_usd"] / 1e6
    L += ["### Demand side: buyer concentration of US exports", "", "![Export buyers](../figures/fig06_export_buyers.png)", "",
          md(bx.rename(columns={"value_usd": f"{fy} value, $M", "n_eff_hhi": f"N_eff {fy}", "top1_country": f"top buyer {fy}",
                                "top1_share": "share", f"n_eff_hhi_{py}": f"N_eff {py}", f"top1_country_{py}": f"top buyer {py}",
                                f"top1_share_{py}": f"share {py}"}),
             {f"{fy} value, $M": "{:,.0f}", f"N_eff {fy}": "{:.1f}", f"N_eff {py}": "{:.1f}", "share": "{:.0%}",
              f"share {py}": "{:.0%}"}), ""]

    # ---------------------------------------------------------------- nowcast
    nsum = load_json("nowcast_summary.json")
    met = pd.read_csv(OUTPUTS / "nowcast_metrics.csv")
    L += ["## 2. Supply nowcast (Permian proxy: Texas + New Mexico crude output)", "",
          "![Nowcast](../figures/fig07_production_nowcast.png)", "",
          f"Out-of-sample, {nsum['sample'][0]} to {nsum['sample'][1]} ({nsum['n']} months), target = monthly log growth, "
          "nowcast made two months before EIA publishes.", "",
          md(met.fillna(""), {"rmse": "{:.4f}", "mae": "{:.4f}", "pinball_q50": "{:.4f}", "dm_vs_ar_stat": "{:.2f}",
                              "dm_vs_ar_p": "{:.3f}"}), "",
          f"Quantile-boosting 10-90 % interval coverage: {nsum.get('gbm_interval_coverage', float('nan')):.0%} "
          f"(nominal 80 %); split-conformal 80 % band around the ridge nowcast: {nsum.get('conformal_coverage', float('nan')):.0%}. "
          "The conformal band, calibrated on the most recent published errors, lands near its nominal level; the boosted "
          "quantile band, which has no calibration step, is too narrow.", "",
          f"Satellite experiment: {nsum['satellite_experiment'] if isinstance(nsum['satellite_experiment'], str) else json.dumps(nsum['satellite_experiment'])}", ""]

    # ---------------------------------------------------------------- regimes
    rs = load_json("regime_summary.json")
    bic = pd.read_csv(OUTPUTS / "regime_bic.csv")
    prof = pd.read_csv(OUTPUTS / "regime_profiles.csv")
    rbr = pd.read_csv(OUTPUTS / "returns_by_regime.csv")
    L += ["## 3. Macro regimes", "", "![Regimes](../figures/fig08_macro_regimes.png)", "",
          md(bic, {"loglik": "{:.1f}", "bic": "{:.1f}"}), "",
          "BIC keeps falling at k = 5, but the five-state model leaves a regime with fewer than 20 months, too few to "
          "condition anything on; the occupancy rule selects k = 4." if (bic.k.max() == 5 and not bool(bic.loc[bic.k == 5, 'eligible'].iloc[0])) else "", "",
          md(prof, {c: "{:.2f}" for c in ["real10", "d12_fedfunds", "cpi_yoy", "d12_unrate", "usd_yoy", "persistence"]}), "",
          f"Latest month {rs['last_month']}: filtered state {rs['current_state_filtered']} "
          f"({json.dumps(rs['current_probs'])}). Filtered and smoothed states agree in "
          f"{rs['agreement_filtered_vs_smoothed']:.0%} of months.", "",
          "![Returns by regime](../figures/fig09_returns_by_regime.png)", "",
          md(rbr, {"mean_pct": "{:.2f}", "vol_pct": "{:.2f}", "se": "{:.2f}", "ann_mean_pct": "{:.1f}"}), ""]

    # ---------------------------------------------------------------- LP
    lps = load_json("lp_summary.json")
    lp = pd.read_csv(OUTPUTS / "lp_wti_supply_surprise.csv")
    show = lp[(lp.h.isin([0, 1, 2, 3, 6, 9, 12])) & (lp.state != "equality_test")].pivot_table(index="h", columns="state", values="beta")
    eq = lp[lp.state == "equality_test"].set_index("h")["hi"].reindex(show.index)
    show["p(equal regimes)"] = eq
    L += ["## 4. Price response to supply surprises (local projections)", "", "![LP](../figures/fig10_lp_supply_surprise.png)", "",
          f"Shock months {lps['shock_sample'][0]} to {lps['shock_sample'][1]}; months by state: {json.dumps(lps['state_months'])}. "
          "Response of 100 x log WTI to a one-standard-deviation upside production surprise:", "",
          md(show.reset_index().astype({"h": int}).astype({"h": str}), {c: "{:.2f}" for c in show.columns}), "",
          "Caveat: the accommodative group is concentrated in 2016 and 2020-21, so the regime contrast partly reflects the "
          "COVID shut-in and rebound; the linear response is the robust result.", ""]

    # ---------------------------------------------------------------- events
    ev = pd.read_csv(OUTPUTS / "event_study_copper_2025.csv")
    L += ["## 5. 2025 copper disruptions (weekly event study)", "", "![Events](../figures/fig11_grasberg_event_study.png)", "",
          md(ev[["name", "ticker", "event_week", "beta", "ar_week0", "t_week0", "car_0_2", "t_car"]],
             {"beta": "{:.2f}", "ar_week0": "{:+.1%}", "t_week0": "{:.2f}", "car_0_2": "{:+.1%}", "t_car": "{:.2f}"}), ""]
    conf = ev[ev.confounded_by.fillna("") != ""]
    for _, r in conf.iterrows():
        L += [f"Confounded: {r['name']} - {r['confounded_by']}.", ""]

    # ---------------------------------------------------------------- satellite
    sat = OUTPUTS / "satellite"
    files = sorted(p.name for p in sat.glob("*.csv")) if sat.exists() else []
    L += ["## 6. Satellite layer", "",
          ("Satellite outputs present: " + ", ".join(f"`{f}`" for f in files) + ".") if files else
          "No satellite outputs in this snapshot. The ingestion code is tested on synthetic GeoTIFFs (`tests/`); run "
          "`bash run.sh --live` on a machine with internet, or the `satellite-ingest` GitHub Actions workflow, to populate "
          "`outputs/satellite/` and feed the nowcast and event tests above.", ""]

    REPORTS.mkdir(exist_ok=True)
    (REPORTS / "RESULTS.md").write_text("\n".join(L) + "\n")
    print(f"wrote {REPORTS / 'RESULTS.md'} ({len(L)} lines)")


if __name__ == "__main__":
    main()
